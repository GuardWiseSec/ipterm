// Builds src/landmask.js, the land bitmask behind `curl ipterm.net/me`'s Braille world map, from the
// browser map's outlines in public/land.js (Natural Earth, public domain, via world-atlas).
//
// There is no build step, so the output is checked in. Run this after changing public/land.js:
//   node tools/build_landmask.mjs
//
// The mask is a 1-degree grid, 360 columns (180°W to 180°E) by 180 rows (90°N to 90°S), one bit per
// cell, rows top to bottom, most significant bit first, stored as base64. A cell is land when at least
// half of a 4x4 grid of sample points inside it is, filled even-odd like the browser map
// (mctx.fill(path, 'evenodd') in public/app.js).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = new URL('..', import.meta.url);
const src = readFileSync(new URL('public/land.js', root), 'utf8');
const sandbox = { window: {} };
vm.runInNewContext(src, sandbox);
const land = sandbox.window.IPTERM_GEO && sandbox.window.IPTERM_GEO.land;
if (!Array.isArray(land)) throw new Error('public/land.js did not define IPTERM_GEO.land');

// Rings are delta-encoded [x, y, dx, dy, ...] in 1/20 degree units, x = longitude, y = latitude.
// Some rings cross the antimeridian by jumping from 180 to -180 (Eurasia does it at 65°N and 69°N,
// leaving Chukotka on the far left). Filled as they are, those jumps flip even-odd parity across the
// whole band between them, so each ring is first unwrapped into one continuous outline (longitudes
// past ±180 allowed) and drawn three times, shifted by -360, 0 and +360. A ring that goes all the way
// around (Antarctica) is closed along its pole.
const edges = [];
for (const ring of land) {
  const raw = [];
  let x = 0, y = 0;
  for (let i = 0; i < ring.length; i += 2) { x += ring[i]; y += ring[i + 1]; raw.push([x / 20, y / 20]); }
  const pts = [raw[0]];
  let shift = 0;
  for (let i = 1; i <= raw.length; i++) {
    const [px, py] = raw[i % raw.length], dx = px - raw[i - 1][0];
    if (dx > 180) shift -= 360; else if (dx < -180) shift += 360;
    if (i < raw.length) pts.push([px + shift, py]);
    else if (shift) {                                    // went around the globe: close along the pole
      const pole = raw.reduce((a, p) => a + p[1], 0) / raw.length < 0 ? -90 : 90;
      pts.push([pts[pts.length - 1][0], pole], [raw[0][0], pole]);   // then the closing edge runs up to the start
    }
  }
  for (const off of [-360, 0, 360]) {
    for (let i = 0; i < pts.length; i++) {
      const a = pts[i], b = pts[(i + 1) % pts.length];
      edges.push([[a[0] + off, a[1]], [b[0] + off, b[1]]]);
    }
  }
}

const W = 360, H = 180, SUB = 4;
const bits = new Uint8Array(W * H / 8);
let landCells = 0;
for (let row = 0; row < H; row++) {
  const counts = new Uint8Array(W);
  for (let sy = 0; sy < SUB; sy++) {
    const lat = 90 - row - (sy + 0.5) / SUB;
    // Even-odd scanline: where every edge crosses this latitude, sorted; inside between pairs.
    const xs = [];
    for (const [[x1, y1], [x2, y2]] of edges) {
      if ((y1 <= lat && lat < y2) || (y2 <= lat && lat < y1)) xs.push(x1 + (lat - y1) * (x2 - x1) / (y2 - y1));
    }
    xs.sort((a, b) => a - b);
    for (let col = 0; col < W; col++) {
      for (let sx = 0; sx < SUB; sx++) {
        const lon = -180 + col + (sx + 0.5) / SUB;
        let n = 0;
        while (n < xs.length && xs[n] <= lon) n++;
        if (n % 2) counts[col]++;
      }
    }
  }
  for (let col = 0; col < W; col++) {
    if (counts[col] * 2 >= SUB * SUB) { const i = row * W + col; bits[i >> 3] |= 0x80 >> (i & 7); landCells++; }
  }
}

const out = `// Generated by tools/build_landmask.mjs from public/land.js (Natural Earth, public domain). Do not edit:
// change public/land.js and run \`node tools/build_landmask.mjs\` instead.
// A 1-degree land grid for the Braille map in \`curl ipterm.net/me\`: ${W} columns from 180°W, ${H} rows from
// 90°N, one bit per cell (1 = land), row by row, most significant bit first, base64. ${landCells} land cells.
export const LAND_MASK = {
  w: ${W},
  h: ${H},
  bits: '${Buffer.from(bits).toString('base64')}',
};
`;
const dest = new URL('src/landmask.js', root);
writeFileSync(dest, out);
console.log(`wrote ${fileURLToPath(dest)}: ${W}x${H}, ${landCells} land cells, ${out.length} bytes`);
